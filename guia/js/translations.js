// Función para cambiar idioma
function changeLanguage(lang) {
    // Guardar idioma en localStorage
    localStorage.setItem('selectedLanguage', lang);
    
    // Actualizar botones activos
    document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.remove('active'));
    const langBtn = document.getElementById('lang-' + lang);
    if (langBtn) {
        langBtn.classList.add('active');
    }
    
    // Actualizar lang del HTML
    const htmlLang = document.getElementById('htmlLang');
    if (htmlLang) {
        htmlLang.setAttribute('lang', lang === 'br' ? 'pt' : lang);
    }
    
    // Actualizar imagen del logo según idioma (solo en paso 1)
    const logoImage = document.getElementById('logoImage');
    if (logoImage) {
        if (lang === 'en') {
            logoImage.src = 'https://www.vetas.com/guia/logoguia_en.jpg';
        } else if (lang === 'br') {
            logoImage.src = 'https://www.vetas.com/guia/logoguia_br.jpg';
        } else {
            logoImage.src = 'logoguia.jpg';
        }
    }
    
    // Actualizar todos los textos
    updateTexts(lang);
    
    // Actualizar campo hidden de idioma
    const langInput = document.querySelector('input[name="lang"]');
    if (langInput) {
        langInput.value = lang;
    }
    
    // Actualizar langField si existe (paso 1)
    const langField = document.getElementById('langField');
    if (langField) {
        langField.value = lang;
    }
}

// Función para actualizar todos los textos
function updateTexts(lang) {
    const t = translations[lang];
    
    // Actualizar títulos y textos con data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key]) {
            if (el.tagName === 'INPUT' && (el.type === 'text' || el.type === 'email' || el.type === 'url' || el.type === 'tel')) {
                el.placeholder = t[key];
            } else if (el.tagName === 'OPTION') {
                el.textContent = t[key];
            } else {
                el.textContent = t[key];
            }
        }
    });
    
    // Actualizar título de la página
    if (t.pageTitle) {
        document.title = t.pageTitle;
    }
}

// Cargar idioma guardado al inicio
document.addEventListener('DOMContentLoaded', function() {
    const savedLang = localStorage.getItem('selectedLanguage') || 'es';
    changeLanguage(savedLang);
});
